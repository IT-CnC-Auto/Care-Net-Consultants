create table public.sales_consultant (
  ghl_user_id  text primary key,
  display_name text not null,
  user_id      uuid unique references public.user_profiles(id),
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

comment on table public.sales_consultant is
  'Bridge between GHL user IDs (pipeline data) and portal accounts (auth). '
  'user_id NULL = consultant has no portal account yet and cannot read briefs. '
  'Writes via service role only. Owner: MA-CN-003 build (CNC-IT-SAL-003).';

